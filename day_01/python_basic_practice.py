import random


# =====================================================================
# 실습 1. 변수와 덧셈 (day_01_01.py)
# =====================================================================
# 목표: 변수에 정수를 저장하고 계산 결과를 출력한다.
# 핵심: 변수, + 연산자, print()
# 직접 풀기:
#   1. number1에 100, number2에 200을 저장한다.
#   2. 두 변수의 합을 출력한다.
# 예상 결과: number1 + number2= 300
# 추가 도전: 뺄셈, 곱셈, 나눗셈 결과도 출력한다.

def practice_1():
    number1 = 100
    number2 = 200
    print("number1 + number2=", number1 + number2)


# =====================================================================
# 실습 2. 점수로 합격 판단하기 (day_01_02.py)
# =====================================================================
# 목표: 입력받은 점수를 정수로 바꾸고 조건에 따라 다른 결과를 출력한다.
# 핵심: input(), int(), >=, if/else
# 직접 풀기:
#   1. 사용자에게 점수를 입력받는다.
#   2. 입력값을 int()로 정수로 변환한다. input()의 결과는 문자열이다.
#   3. 60 이상이면 '합격', 그 외에는 '불합격'을 출력한다.
# 확인 입력: 59 -> 불합격 / 60 -> 합격 / 100 -> 합격
# 추가 도전: 90 이상 A, 80 이상 B, 70 이상 C, 나머지 D로 분류한다.
#            높은 점수 조건부터 if/elif/else로 검사한다.

def practice_2():
    score = int(input("점수를 입력하세요: "))
    if score >= 60:
        print("합격")
    else:
        print("불합격")


# =====================================================================
# 실습 3. 리스트에 저장하고 짝수 찾기 (day_01_03.py)
# =====================================================================
# 목표: 반복해서 입력받은 값을 리스트에 저장하고 짝수만 출력한다.
# 핵심: [], append(), for, range(), %, f-string
# 직접 풀기:
#   1. 빈 리스트 scores를 만든다.
#   2. range(5)로 다섯 번 반복하며 정수를 입력받는다.
#   3. append()로 입력한 정수를 리스트 끝에 추가한다.
#   4. 리스트 전체를 출력한 뒤 각 값에 대해 짝수인지 검사한다.
# 힌트: n % 2 == 0이면 짝수이다. range(5)는 0~4를 생성한다.
# 확인 입력: 1, 2, 3, 4, 5 -> 짝수 출력은 2와 4
# 추가 도전: 홀수만 출력하거나, 입력받을 숫자의 개수를 사용자에게 받는다.

def practice_3():
    scores = []
    for i in range(5):
        score = int(input(f"{i + 1}번째 숫자를 입력하세요: "))
        scores.append(score)

    print("리스트변수의 값:", scores)
    print("짝수:")
    for number in scores:
        if number % 2 == 0:
            print(number)


# =====================================================================
# 실습 4. 중첩 반복문으로 구구단 출력하기 (day_01_04.py)
# =====================================================================
# 목표: 한 줄에 2~9단의 같은 곱셈 순서를 가로로 출력한다.
# 핵심: 중첩 for, range(시작, 끝), f-string, end, \t, \n
# 직접 풀기:
#   1. 바깥 반복문에서 곱하는 수를 1~9로 바꾼다.
#   2. 안쪽 반복문에서 단을 2~9로 바꾼다.
#   3. '2 x 1 = 2' 형태로 출력하고 end="\t"로 칸을 나눈다.
#   4. 안쪽 반복문이 끝나면 print()로 다음 줄로 이동한다.
# 힌트: range(2, 10)의 마지막 값은 9이다. 끝값 10은 포함하지 않는다.
# 첫 줄: 2 x 1 = 2    3 x 1 = 3    ...    9 x 1 = 9
# 마지막 줄: 2 x 9 = 18    3 x 9 = 27    ...    9 x 9 = 81
# 추가 도전: 바깥과 안쪽 반복문의 역할을 바꿔 단별로 세로 출력한다.

def practice_4():
    for multiplier in range(1, 10):
        for dan in range(2, 10):
            print(f"{dan} x {multiplier} = {dan * multiplier}", end="\t")
        print()


# =====================================================================
# 실습 5. 숫자 맞추기 게임 (day_01_05.py)
# =====================================================================
# 목표: 난수를 만들고 정답을 맞힐 때까지 입력과 비교를 반복한다.
# 핵심: import random, randint(), while True, if/elif/else, +=, break
# 직접 풀기:
#   1. random.randint(1, 100)으로 정답을 만든다. 1과 100도 포함된다.
#   2. 시도 횟수를 0으로 초기화한다.
#   3. while True 안에서 정수를 입력받고 시도 횟수를 1 증가시킨다.
#   4. 입력이 정답보다 크면 '큽니다', 작으면 '작습니다'를 출력한다.
#   5. 정답이면 시도 횟수를 출력하고 break로 반복을 끝낸다.
# 확인 방법: 잠시 정답을 50으로 고정하고 80, 20, 50을 입력한다.
#            차례대로 '큽니다', '작습니다', '정답 ... 3'이 나와야 한다.
#            확인 후 정답 생성 코드를 randint()로 되돌린다.
# 추가 도전: 시도 횟수를 7회로 제한한다.
#            1~100 범위 밖의 입력은 시도 횟수에 포함하지 않는다.
#            try/except ValueError로 정수가 아닌 입력을 처리한다.

def practice_5():
    com_number = random.randint(1, 100)
    count = 0

    while True:
        user_number = int(input("1~100 사이의 정수를 입력하세요: "))
        count += 1

        if user_number > com_number:
            print("컴퓨터 숫자보다 큽니다.")
        elif user_number < com_number:
            print("컴퓨터 숫자보다 작습니다.")
        else:
            print(f"정답입니다. 총 시도 횟수: {count}")
            break


# 아래 함수와 메뉴는 여러 실습을 한 파일에서 실행하기 위한 구성입니다.
# def는 실행할 코드를 묶는 함수 정의이며, practice_1()처럼 호출합니다.
def main():
    while True:
        print("\n===== Python 기초 복습 실습장 =====")
        print("1. 변수와 덧셈")
        print("2. 점수로 합격 판단하기")
        print("3. 리스트와 짝수 찾기")
        print("4. 중첩 반복문과 구구단")
        print("5. 숫자 맞추기 게임")
        print("0. 종료")
        choice = input("실습 번호를 선택하세요: ").strip()

        if choice == "0":
            print("실습을 종료합니다.")
            break
        elif choice == "1":
            practice_1()
        elif choice == "2":
            practice_2()
        elif choice == "3":
            practice_3()
        elif choice == "4":
            practice_4()
        elif choice == "5":
            practice_5()
        else:
            print("0~5 중에서 선택하세요.")


# 이 파일을 직접 실행할 때 메뉴를 시작합니다.
if __name__ == "__main__":
    main()
